-- Account Focus · 02 tables. Safe to re-run (CREATE IF NOT EXISTS keeps your data).
USE ROLE ACCOUNT_FOCUS_ADMIN;
USE WAREHOUSE ACCOUNT_FOCUS_WH;
USE SCHEMA ACCOUNT_FOCUS.CORE;

-- Inputs. Each row keeps the full record as VARIANT so the engine reads the same shape offline and live.
CREATE TABLE IF NOT EXISTS AF_ACCOUNT  (K STRING PRIMARY KEY, ACCOUNT_KEY STRING, DATA VARIANT, LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP());
CREATE TABLE IF NOT EXISTS AF_SIGNAL   (K STRING PRIMARY KEY, ACCOUNT_KEY STRING, DATA VARIANT, LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP());
CREATE TABLE IF NOT EXISTS AF_CONTACT  (K STRING PRIMARY KEY, ACCOUNT_KEY STRING, DATA VARIANT, LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP());
CREATE TABLE IF NOT EXISTS AF_VALUEMAP (K STRING, ACCOUNT_KEY STRING, DATA VARIANT);
CREATE TABLE IF NOT EXISTS AF_DRAFT    (ACCOUNT_KEY STRING PRIMARY KEY, DATA VARIANT) COMMENT = 'Scripted agent wording, used when MODEL = scripted';
CREATE TABLE IF NOT EXISTS AF_PREP     (ACCOUNT_KEY STRING PRIMARY KEY, DATA VARIANT);
CREATE TABLE IF NOT EXISTS AF_CATALOG  (DATA VARIANT) COMMENT = 'Seller catalog: value propositions and proof points';
CREATE TABLE IF NOT EXISTS AF_CONFIG   (K STRING PRIMARY KEY, V STRING) COMMENT = 'demo_today pins the demo date; model is scripted or cortex';
CREATE TABLE IF NOT EXISTS AF_SEGMENT  (DATA VARIANT) COMMENT = 'Labelled call segments for the extraction check (synthetic)';
CREATE TABLE IF NOT EXISTS AF_BACKTEST (DATA VARIANT) COMMENT = 'Synthetic weekly history for the ranking backtest';

-- Outputs. Append-only, so any past run can be replayed exactly.
CREATE TABLE IF NOT EXISTS AF_RUN (
  RUN_ID NUMBER AUTOINCREMENT PRIMARY KEY, CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
  AS_OF DATE, VERSION STRING, MODEL STRING, PAYLOAD VARIANT);
CREATE TABLE IF NOT EXISTS AF_SCORE (
  RUN_ID NUMBER, AS_OF DATE, ACCOUNT_KEY STRING, ACCOUNT_NAME STRING, MOTION STRING,
  ATTRACTIVENESS NUMBER, MOMENTUM NUMBER, READINESS NUMBER, CONFIDENCE NUMBER, PRIORITY NUMBER,
  ACTION STRING, SLOT STRING, RANK NUMBER, WHY_NOW STRING, EVIDENCE ARRAY);

-- Seller decisions, hand-offs to GTM Orbit, and the audit trail.
CREATE TABLE IF NOT EXISTS AF_FEEDBACK (
  ACCOUNT_KEY STRING, DECISION STRING, REASON STRING, ACTOR STRING, VIA STRING, DAY DATE,
  AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
  CONSTRAINT AF_FEEDBACK_DECISION CHECK (DECISION IN ('accepted', 'snoozed', 'rejected')));
CREATE TABLE IF NOT EXISTS AF_HANDOFF (ACCOUNT_KEY STRING, PAYLOAD VARIANT, AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP())
  COMMENT = 'Accounts handed to GTM Orbit''s outreach brief, with Focus context';
CREATE TABLE IF NOT EXISTS AF_AUDIT (AT TIMESTAMP_NTZ, ACTOR STRING, EVENT STRING, LEVEL STRING, DETAIL STRING);
