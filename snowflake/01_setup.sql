-- Account Focus · 01 setup: role, warehouse, database and schema.
-- Run as ACCOUNTADMIN (or a role that can create roles, warehouses and databases).
-- Safe to re-run.
USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS ACCOUNT_FOCUS_ADMIN COMMENT = 'Owns Account Focus objects';
SET MY_USER = CURRENT_USER();
GRANT ROLE ACCOUNT_FOCUS_ADMIN TO USER IDENTIFIER($MY_USER);
GRANT ROLE ACCOUNT_FOCUS_ADMIN TO ROLE SYSADMIN;

CREATE WAREHOUSE IF NOT EXISTS ACCOUNT_FOCUS_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  COMMENT = 'Account Focus scoring and app queries';
GRANT USAGE, OPERATE ON WAREHOUSE ACCOUNT_FOCUS_WH TO ROLE ACCOUNT_FOCUS_ADMIN;

CREATE DATABASE IF NOT EXISTS ACCOUNT_FOCUS COMMENT = 'Account Focus: the daily decision layer inside GTM Orbit (fictional demo data)';
GRANT OWNERSHIP ON DATABASE ACCOUNT_FOCUS TO ROLE ACCOUNT_FOCUS_ADMIN COPY CURRENT GRANTS;

USE ROLE ACCOUNT_FOCUS_ADMIN;
CREATE SCHEMA IF NOT EXISTS ACCOUNT_FOCUS.CORE COMMENT = 'Inputs, scoring runs, decisions and audit';

-- Cortex is optional. Scripted mode needs no AI functions; live model mode needs this grant.
USE ROLE ACCOUNTADMIN;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE ACCOUNT_FOCUS_ADMIN;
