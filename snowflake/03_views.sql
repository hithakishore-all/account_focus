-- Account Focus · 03 views for analysts, dashboards and other agents (for example GTM Orbit via MCP).
USE ROLE ACCOUNT_FOCUS_ADMIN;
USE WAREHOUSE ACCOUNT_FOCUS_WH;
USE SCHEMA ACCOUNT_FOCUS.CORE;

-- Every signal, typed. source_side tells public evidence from internal evidence.
CREATE OR REPLACE VIEW V_SIGNAL AS
SELECT DATA:ref::STRING AS EVIDENCE_REF, ACCOUNT_KEY, DATA:side::STRING AS SOURCE_SIDE, DATA:source::STRING AS SOURCE_SYSTEM,
       DATA:family::STRING AS FAMILY, DATA:type::STRING AS SIGNAL_TYPE, DATA:date::DATE AS OCCURRED_ON, DATA:strength::FLOAT AS STRENGTH,
       DATA:polarity::STRING AS POLARITY, DATA:speaker::STRING AS SPEAKER, DATA:speaker_side::STRING AS SPEAKER_SIDE,
       DATA:speaker_matched::BOOLEAN AS SPEAKER_MATCHED, DATA:event::STRING AS EVENT_KEY, DATA:text::STRING AS EVIDENCE_TEXT
FROM AF_SIGNAL;

-- Scores from the latest run, one row per account.
CREATE OR REPLACE VIEW V_LATEST_SCORE AS
SELECT * FROM AF_SCORE WHERE RUN_ID = (SELECT MAX(RUN_ID) FROM AF_RUN);

-- Today's brief: the five picks with today's decisions, in pick order.
CREATE OR REPLACE VIEW V_BRIEF AS
WITH run AS (SELECT RUN_ID, AS_OF, PAYLOAD FROM AF_RUN QUALIFY ROW_NUMBER() OVER (ORDER BY RUN_ID DESC) = 1),
picks AS (SELECT p.index + 1 AS POSITION, p.value::STRING AS ACCOUNT_KEY, r.AS_OF FROM run r, LATERAL FLATTEN(INPUT => r.PAYLOAD:brief:picks) p)
SELECT picks.POSITION, s.ACCOUNT_KEY, s.ACCOUNT_NAME, s.MOTION, s.PRIORITY, s.ATTRACTIVENESS, s.MOMENTUM, s.READINESS, s.CONFIDENCE,
       s.ACTION, s.SLOT, s.WHY_NOW, s.EVIDENCE, f.DECISION, f.REASON, f.ACTOR AS DECIDED_BY
FROM picks JOIN V_LATEST_SCORE s ON s.ACCOUNT_KEY = picks.ACCOUNT_KEY
LEFT JOIN AF_FEEDBACK f ON f.ACCOUNT_KEY = picks.ACCOUNT_KEY AND f.DAY = picks.AS_OF
ORDER BY picks.POSITION;

-- Acceptance and reject reasons: the first numbers a pilot reviews.
CREATE OR REPLACE VIEW V_FEEDBACK_SUMMARY AS
SELECT DAY, COUNT(*) AS DECISIONS,
       COUNT_IF(DECISION = 'accepted') AS ACCEPTED, COUNT_IF(DECISION = 'snoozed') AS SNOOZED, COUNT_IF(DECISION = 'rejected') AS REJECTED,
       ROUND(COUNT_IF(DECISION = 'accepted') / NULLIF(COUNT(*), 0), 3) AS ACCEPTANCE_RATE,
       ARRAY_AGG(DISTINCT REASON) AS REASONS_SEEN
FROM AF_FEEDBACK GROUP BY DAY;
