-- Account Focus · 06 service user for the Node app (key-pair login, no password).
-- Before running: create a key pair (docs/SETUP_SNOWFLAKE.md, step 5) and paste the PUBLIC key body below,
-- without the BEGIN/END lines. The private key stays on your computer in app/.keys/ (git-ignored).
USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS ACCOUNT_FOCUS_APP COMMENT = 'Least privilege: read runs, write decisions, hand-offs and audit';
GRANT USAGE ON WAREHOUSE ACCOUNT_FOCUS_WH TO ROLE ACCOUNT_FOCUS_APP;
GRANT USAGE ON DATABASE ACCOUNT_FOCUS TO ROLE ACCOUNT_FOCUS_APP;
GRANT USAGE ON SCHEMA ACCOUNT_FOCUS.CORE TO ROLE ACCOUNT_FOCUS_APP;
GRANT SELECT ON TABLE ACCOUNT_FOCUS.CORE.AF_RUN TO ROLE ACCOUNT_FOCUS_APP;
GRANT SELECT, INSERT ON TABLE ACCOUNT_FOCUS.CORE.AF_FEEDBACK TO ROLE ACCOUNT_FOCUS_APP;
GRANT SELECT, INSERT ON TABLE ACCOUNT_FOCUS.CORE.AF_AUDIT TO ROLE ACCOUNT_FOCUS_APP;
GRANT INSERT ON TABLE ACCOUNT_FOCUS.CORE.AF_HANDOFF TO ROLE ACCOUNT_FOCUS_APP;
GRANT SELECT ON VIEW ACCOUNT_FOCUS.CORE.V_BRIEF TO ROLE ACCOUNT_FOCUS_APP;
GRANT SELECT ON VIEW ACCOUNT_FOCUS.CORE.V_LATEST_SCORE TO ROLE ACCOUNT_FOCUS_APP;
GRANT SELECT ON TABLE ACCOUNT_FOCUS.CORE.AF_SCORE TO ROLE ACCOUNT_FOCUS_APP;

CREATE USER IF NOT EXISTS ACCOUNT_FOCUS_SVC
  TYPE = SERVICE
  DEFAULT_ROLE = ACCOUNT_FOCUS_APP
  DEFAULT_WAREHOUSE = ACCOUNT_FOCUS_WH
  COMMENT = 'Account Focus Node app';
ALTER USER ACCOUNT_FOCUS_SVC SET RSA_PUBLIC_KEY = 'PASTE_PUBLIC_KEY_BODY_HERE';
GRANT ROLE ACCOUNT_FOCUS_APP TO USER ACCOUNT_FOCUS_SVC;

-- Check: DESC USER ACCOUNT_FOCUS_SVC;  RSA_PUBLIC_KEY_FP should show a fingerprint.
