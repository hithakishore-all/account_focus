#!/usr/bin/env node
'use strict';
// Builds snowflake/08_sync_salesforce.sql from a Salesforce export, so Snowflake accounts carry your
// org's real record IDs (links in the console then open the right Salesforce record).
//   1. ../scripts/export-salesforce.sh <org-alias>      writes salesforce/exports/accounts.json
//   2. npm run sync-sql                                  writes snowflake/08_sync_salesforce.sql
//   3. run 08_sync_salesforce.sql in Snowflake, then CALL SP_SCORE_ALL('scripted');
// Without Salesforce, use snowflake/08_sync_salesforce.sample.sql (stand-in IDs) or skip this step.
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..', '..');
const sample = process.argv.includes('--sample');
let rows;
if (sample) {
  rows = require('../../data/seed/accounts.json').map((a) => ({ Id: a.salesforce_id, AccountNumber: a.key }));
} else {
  const file = path.join(root, 'salesforce', 'exports', 'accounts.json');
  if (!fs.existsSync(file)) { console.error('No export found at salesforce/exports/accounts.json. Run scripts/export-salesforce.sh first, or use --sample.'); process.exit(1); }
  const j = JSON.parse(fs.readFileSync(file, 'utf8'));
  rows = (j.result && j.result.records) || [];
}
const bad = rows.filter((r) => !/^[a-zA-Z0-9]{15,18}$/.test(r.Id) || !/^GTM-\d{4}$/.test(r.AccountNumber || ''));
if (bad.length) { console.error('Unexpected rows in the export:', bad.slice(0, 3)); process.exit(1); }
const lines = [
  `-- Account Focus · 08 sync Salesforce IDs. GENERATED by app/scripts/build-sync-sql.js${sample ? ' --sample (stand-in IDs)' : ''}.`,
  'USE ROLE ACCOUNT_FOCUS_ADMIN;', 'USE WAREHOUSE ACCOUNT_FOCUS_WH;', 'USE SCHEMA ACCOUNT_FOCUS.CORE;', ''];
rows.forEach((r) => lines.push(`UPDATE AF_ACCOUNT SET DATA = OBJECT_INSERT(DATA, 'salesforce_id', '${r.Id}', TRUE) WHERE K = '${r.AccountNumber}';`));
lines.push('', "CALL SP_SCORE_ALL('scripted');", '');
const out = path.join(root, 'snowflake', sample ? '08_sync_salesforce.sample.sql' : '08_sync_salesforce.sql');
fs.writeFileSync(out, lines.join('\n'));
console.log(`Wrote ${path.relative(process.cwd(), out)} (${rows.length} accounts).`);
